function normalizeMockServiceCategories(serviceCategory) {
    if (Array.isArray(serviceCategory)) {
        return serviceCategory.map((v) => String(v ?? '').trim()).filter((v) => v && v !== '—')
    }
    const text = String(serviceCategory ?? '').trim()
    if (!text || text === '—') return []
    return text
        .split(/[,;\n]/)
        .map((v) => v.trim())
        .filter(Boolean)
}

function row({
    id,
    employee,
    project,
    category,
    serviceCategory = '—',
    amount,
    status,
    createdAt,
    modifiedAt = '',
    instanceId,
    activityId,
    currentStep,
    source,
    assignedToNames = [],
    closedByNames = [],
    claimMonth = '—',
}) {
    const closed = /approv|complete|reject/i.test(status)
    const serviceCategories = normalizeMockServiceCategories(serviceCategory)
    return {
        id,
        claimMonth,
        employee,
        project,
        category,
        serviceCategories,
        serviceCategory: serviceCategories.length ? serviceCategories.join(', ') : '—',
        amount,
        status,
        date: createdAt,
        createdAt,
        modifiedAt,
        closedOn: closed ? modifiedAt : '',
        instanceId,
        activityId,
        currentStep,
        source,
        assignedTo: assignedToNames.length ? assignedToNames.join(', ') : '—',
        assignedToNames,
        closedBy: closedByNames.length ? closedByNames.join(', ') : '—',
        closedByNames,
    }
}

